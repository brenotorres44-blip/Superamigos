window.importarSacolinhas = async () => {
  const existentes = new Set(sacolinhas.map(s => Number(s.numero)));
  const novos = DADOS_SACOLINHAS.filter(d => !existentes.has(d.numero));

  if (!novos.length) {
    toast('✅ Todas as ' + DADOS_SACOLINHAS.length + ' crianças da lista já estão cadastradas!');
    return;
  }

  const ok = await confirmar(
    'Importar ' + novos.length + ' crianças da lista oficial? ' +
    (existentes.size ? '(' + (DADOS_SACOLINHAS.length - novos.length) + ' já cadastradas serão ignoradas)' : '')
  );
  if (!ok) return;

  toast('⏳ Importando ' + novos.length + ' crianças… aguarde, não feche a página.', 6000);

  try {
    // Firestore aceita até 500 gravações por lote
    for (let i = 0; i < novos.length; i += 450) {
      const lote = novos.slice(i, i + 450);
      const batch = writeBatch(db);
      lote.forEach(d => {
        const ref = doc(collection(db, 'sacolinhas'));
        batch.set(ref, {
          numero:     d.numero,
          comunidade: d.comunidade,
          nome:       d.nome,
          sexo:       d.sexo || '',
          idade:      '',
          roupa:      '',
          calcado:    '',
          necesp:     'Não',
          entrega:    '',
          obs:        '',
          status:     'aguardando',
          criadoEm:   serverTimestamp()
        });
      });
      await batch.commit();
      toast('⏳ ' + Math.min(i + 450, novos.length) + ' de ' + novos.length + ' importadas…', 4000);
    }
    toast('🎉 Importação concluída! ' + novos.length + ' crianças cadastradas.', 6000);
  } catch (e) {
    console.error(e);
    toast('❌ Erro na importação. Verifique a conexão e tente novamente.', 6000);
  }
};
